-- Client account. Referenced by limits and transactions; its row is locked (SELECT ... FOR UPDATE)
-- while a transaction is processed, so concurrent transactions of one client are handled one by one.
CREATE TABLE account
(
    number VARCHAR(10) PRIMARY KEY
);

-- Monthly spending limits. Rows are only inserted, never updated: a new limit is a new row.
CREATE TABLE spending_limit
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(10)    NOT NULL REFERENCES account (number),
    category       VARCHAR(10)    NOT NULL CHECK (category IN ('PRODUCT', 'SERVICE')),
    amount         NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    currency       VARCHAR(3)     NOT NULL,
    set_at         TIMESTAMPTZ    NOT NULL
);

-- Finding the limit active at a given moment: last row of the account and category with set_at <= moment
CREATE INDEX idx_spending_limit_account_category_set_at
    ON spending_limit (account_number, category, set_at);

-- Daily close rates: how many USD one unit of the currency costs
CREATE TABLE exchange_rate
(
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency  VARCHAR(3)     NOT NULL,
    rate_date DATE           NOT NULL,
    rate      NUMERIC(20, 10) NOT NULL CHECK (rate > 0),
    CONSTRAINT uq_exchange_rate_currency_date UNIQUE (currency, rate_date)
);

CREATE TABLE expense_transaction
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_from   VARCHAR(10)    NOT NULL REFERENCES account (number),
    account_to     VARCHAR(10)    NOT NULL,
    currency       VARCHAR(3)     NOT NULL,
    sum            NUMERIC(19, 2) NOT NULL CHECK (sum > 0),
    category       VARCHAR(10)    NOT NULL CHECK (category IN ('PRODUCT', 'SERVICE')),
    datetime       TIMESTAMPTZ    NOT NULL,
    sum_usd        NUMERIC(19, 2) NOT NULL,
    limit_exceeded BOOLEAN        NOT NULL,
    -- The limit that was active when the transaction was made
    limit_id       BIGINT         NOT NULL REFERENCES spending_limit (id)
);

-- Summing the month's expenses of an account and category
CREATE INDEX idx_expense_transaction_account_category_datetime
    ON expense_transaction (account_from, category, datetime);
